def emit_enum(name: str, schema: Any) -> str:
    """A Java enum for a string-enum schema, with its wire spelling attached."""
    type_name = pascal(name)
    lines = [BANNER.rstrip("\n"), f"package {MODELS_PACKAGE};", "",
             "import com.fasterxml.jackson.annotation.JsonCreator;",
             "import com.fasterxml.jackson.annotation.JsonValue;", ""]
    lines.extend(javadoc(
        (schema.get("description") or f"The {type_name} values the server defines.")
        + "\n\nThe wire spelling is carried on each constant rather than derived "
          "from its name, because the server's vocabulary is not uniformly cased "
          "and a derivation that worked for every value today would break on the "
          "first one that did not fit."))
    lines.append(f"public enum {type_name} {{")
    values = [v for v in schema["enum"] if isinstance(v, str)]
    for value in values:
        lines.extend(inline_javadoc(f"The server's {value!r} value.", "    "))
        lines.append(f'    {enum_constant(value)}("{value}"),')
    lines.extend(javadoc(
        "A value this SDK's copy of the spec does not list.\n\n"
        "CONTRACT §27.11 rule 1: an unrecognised value MUST decode rather than "
        "failing the response it arrived in. A closed enum turns the next value "
        "the server adds into a parse error on the whole `list`, taking down "
        "every record on the page over one field of one of them -- including the "
        "records the caller was actually after.\n\n"
        "A Java enum constant cannot carry the string it was decoded from, so "
        "this one does not pretend to. Its wire spelling is the empty string, "
        "which no server value is: fifteen of these enums appear in request "
        "bodies, and a read-modify-write that carried an unrecognised value back "
        "is refused by the server with a 400 rather than silently writing a "
        "spelling it never used. Do not send it deliberately -- read the field, "
        "and if it is {@code UNKNOWN}, leave it out of the update.",
        "    "))
    lines.append('    UNKNOWN("");')
    lines.append("")
    lines.append("    /** The spelling this value has on the wire. */")
    lines.append("    private final String wire;")
    lines.append("")
    lines.append(f"    {type_name}(String wire) {{")
    lines.append("        this.wire = wire;")
    lines.append("    }")
    lines.append("")
    lines.extend(javadoc(
        "Returns the spelling this value has on the wire.\n\n"
        "{@link #UNKNOWN} answers the empty string, which is not a value any "
        "server sends. That is deliberate: it is what makes carrying an "
        "unrecognised value back into an update a 400 from the server rather "
        "than a silent rewrite into a spelling it never used. This accessor "
        "cannot throw, because Jackson calls it on every constant while building "
        "its deserializer -- a throwing one would break decoding for the whole "
        "enum, which is the failure this type exists to avoid.",
        "    ",
        ["@return the server's own spelling of this value, or the empty string "
         "for {@link #UNKNOWN}"]))
    lines.append("    @JsonValue")
    lines.append("    public String wire() {")
    lines.append("        return wire;")
    lines.append("    }")
    lines.append("")
    lines.extend(javadoc(
        "Parses a wire value into a constant.\n\nAn unrecognised value yields "
        "{@link #UNKNOWN} rather than throwing (CONTRACT §27.11 rule 1). Failing "
        "here would fail the whole response, so one field of one record the "
        "caller did not ask about would take down the page. A caller that cares "
        "compares against {@code UNKNOWN}; one that does not gets the rest of "
        "the record intact.",
        "    ",
        ["@param value the server's spelling",
         f"@return the matching {type_name}, or {{@link #UNKNOWN}}"]))
    lines.append("    @JsonCreator")
    lines.append(f"    public static {type_name} fromWire(String value) {{")
    lines.append(f"        for ({type_name} candidate : values()) {{")
    lines.append("            if (candidate != UNKNOWN && candidate.wire.equals(value)) {")
    lines.append("                return candidate;")
    lines.append("            }")
    lines.append("        }")
    lines.append("        return UNKNOWN;")
    lines.append("    }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def component_lines(fields: list[dict[str, Any]]) -> list[str]:
    """The record components, one per line, with their Jackson names."""
    out: list[str] = []
    for i, f in enumerate(fields):
        tail = "," if i < len(fields) - 1 else ""
        out.append(f'        @JsonProperty("{f["wire"]}") {f["type"]} {f["name"]}{tail}')
    return out


def field_list(schema_name: str, secrets: set[str]) -> tuple[list[dict[str, Any]], set[str], str | None]:
    """The fields of a schema, in a stable order, with Java names and types."""
    props, required, description = flatten(schema_name)
    props = dict(props)
    for add in PROJECTIONS.get(schema_name, []):
        if add["name"] in props:
            continue
        required.discard(add["name"])
        props[add["name"]] = {
            "type": add.get("type"),
            "format": add.get("format"),
            "description": (
                "resolved by the list projection only. The server resolves this for a "
                "whole page in one query, so it is populated by the list operation and "
                "is null on get (CONTRACT §27.11 rule 4). Null there means \"this read "
                "does not carry it\", not \"there is nothing bound\" — the SDK does not "
                "issue a second request to fill it in"
            ),
        }
    fields = []
    for wire in sorted(props):
        fields.append({
            "wire": wire,
            "name": member(wire),
            "type": "Sensitive" if wire in secrets else java_type(props[wire]),
            "required": wire in required,
            "doc": props[wire].get("description") or f"the server's {wire} field",
            "secret": wire in secrets,
        })
    return fields, required, description


def emit_record(name: str, secrets: set[str], replacement: bool) -> str:
    """A Java record for an object schema, plus a builder when it is sparse."""
    type_name = pascal(name)
    fields, required, description = field_list(name, secrets)
    all_optional = bool(fields) and not required

    text = description or f"The {type_name} schema from the server's OpenAPI document."
    if all_optional:
        text += ("\n\nEvery component is optional, so this is a SPARSE body: what you leave "
                 "null is left unchanged, and is omitted from the wire request entirely rather "
                 "than sent as null (§27.4 rule 5). Use the builder — a canonical constructor "
                 "call with six nulls in it is not something a reader can check.")
    elif replacement:
        text += ("\n\nThis body REPLACES rather than patches (§27.4 rule 5): what you do not "
                 "carry over from a prior read is not preserved, it is overwritten. The "
                 "canonical constructor takes every component, so forgetting one is a compile "
                 "error rather than a silent null on the wire.")

    tags = []
    for f in fields:
        doc = f["doc"]
        if f["secret"]:
            doc += " -- SECRET: redacted from toString and from every JSON rendering except " \
                   "the one request body it is sent in"
        tags.append(f"@param {f['name']} {escape(' '.join(str(doc).split()))}")

    body: list[str] = []
    body.extend(javadoc(text, "", tags))
    body.append("@JsonIgnoreProperties(ignoreUnknown = true)")
    body.append("@JsonInclude(JsonInclude.Include.NON_NULL)")
    if not fields:
        body.append(f"public record {type_name}() {{")
        body.append("}")
    else:
        body.append(f"public record {type_name}(")
        for f in fields:
            if not f["required"]:
                f["type"] = f"@Nullable {f['type']}"
        body.extend(component_lines(fields))
        body.append(") {")
        if all_optional:
            body.extend(emit_builder(type_name, fields))
        body.append("}")

    rendered = "\n".join(body)
    header = [BANNER.rstrip("\n"), f"package {MODELS_PACKAGE};", "",
              "import com.fasterxml.jackson.annotation.JsonIgnoreProperties;",
              "import com.fasterxml.jackson.annotation.JsonInclude;",
              "import com.fasterxml.jackson.annotation.JsonProperty;"]
    if "@Nullable" in rendered:
        header.append("import org.jspecify.annotations.Nullable;")
    imports = model_imports(rendered)
    if imports:
        header.append("")
        header.extend(f"import {fqn};" for fqn in imports)
    header.append("")
    return "\n".join(header + [rendered]) + "\n"


def emit_builder(type_name: str, fields: list[dict[str, Any]]) -> list[str]:
    """A nested builder for a sparse body, so unset stays unset."""
    lines = ["", ]
    lines.extend(javadoc(
        f"Starts a {type_name} with nothing set.\n\nEvery field left unset is "
        f"omitted from the wire body entirely, so a builder that sets one field "
        f"changes one field (§27.4 rule 5).",
        "    ", [f"@return a fresh {type_name}.Builder"]))
    lines.append("    public static Builder builder() {")
    lines.append("        return new Builder();")
    lines.append("    }")
    lines.append("")
    lines.extend(javadoc(
        f"Builds a sparse {type_name}.\n\nWhat you do not set is not sent — not "
        f"sent as null, absent from the body altogether.", "    "))
    lines.append("    public static final class Builder {")
    lines.append("")
    # javadoc's doclint flags an implicit default constructor as undocumented,
    # so the builder declares its own rather than inheriting one it cannot
    # comment.
    lines.append("        /** Starts with every field unset. */")
    lines.append("        private Builder() {")
    lines.append("        }")
    lines.append("")
    for f in fields:
        bare = f["type"].replace("@Nullable ", "")
        lines.append(f"        private @Nullable {bare} {f['name']};")
    lines.append("")
    for f in fields:
        bare = f["type"].replace("@Nullable ", "")
        lines.extend(javadoc(
            f"Sets {escape(f['wire'])}.",
            "        ",
            [f"@param {f['name']} the value to send", "@return this builder"]))
        lines.append(f"        public Builder {f['name']}({bare} {f['name']}) {{")
        lines.append(f"            this.{f['name']} = {f['name']};")
        lines.append("            return this;")
        lines.append("        }")
        lines.append("")
    lines.extend(javadoc(
        "Builds the body.", "        ",
        [f"@return a {type_name} carrying exactly the fields that were set"]))
    lines.append(f"        public {type_name} build() {{")
    joined = ", ".join(f["name"] for f in fields)
    lines.append(f"            return new {type_name}({joined});")
    lines.append("        }")
    lines.append("    }")
    return lines


def emit_union(name: str, schema: Any, tag: str, arms: list[tuple[str, Any]]) -> dict[str, str]:
    """A sealed interface plus one record per arm, Jackson-tagged."""
    type_name = pascal(name)
    files: dict[str, str] = {}
    arm_names = [f"{type_name}{pascal(value)}" for value, _ in arms]

    lines = [BANNER.rstrip("\n"), f"package {MODELS_PACKAGE};", "",
             "import com.fasterxml.jackson.annotation.JsonSubTypes;",
             "import com.fasterxml.jackson.annotation.JsonTypeInfo;", ""]
    lines.extend(javadoc(
        (schema.get("description") or f"A {type_name} value.")
        + f"\n\nA closed set of shapes discriminated by the {tag} field. Sealed, so "
          f"a switch over the permitted records is exhaustive and the compiler says "
          f"so — which is what makes adding an arm a compile error at every call "
          f"site rather than a silent fall-through."))
    lines.append(f'@JsonTypeInfo(use = JsonTypeInfo.Id.NAME, include = JsonTypeInfo.As.EXISTING_PROPERTY,')
    lines.append(f'        property = "{tag}", visible = true)')
    lines.append("@JsonSubTypes({")
    for (value, _), arm in zip(arms, arm_names):
        lines.append(f'        @JsonSubTypes.Type(value = {arm}.class, name = "{value}"),')
    lines.append("})")
    lines.append(f"public sealed interface {type_name} permits " + ", ".join(arm_names) + " {")
    lines.append("")
    lines.extend(javadoc(
        f"Returns the discriminator this arm carries.", "    ",
        [f"@return the server's {escape(tag)} value for this arm"]))
    lines.append(f"    String {member(tag)}();")
    lines.append("}")
    files[f"{MODELS_DIR}/{type_name}.java"] = "\n".join(lines) + "\n"

    for (value, payload), arm in zip(arms, arm_names):
        if "$ref" in payload:
            props, required, desc = flatten(payload["$ref"].split("/")[-1])
        else:
            props = payload.get("properties") or {}
            required = set(payload.get("required") or [])
            desc = payload.get("description")
        fields = [{
            "wire": w, "name": member(w), "type": java_type(props[w]),
            "required": w in required, "doc": props[w].get("description") or f"the server's {w} field",
            "secret": False,
        } for w in sorted(props) if w != tag]

        arm_lines: list[str] = []
        tags = [f"@param {member(tag)} the discriminator, always {value!r}"]
        for f in fields:
            tags.append(f"@param {f['name']} {escape(' '.join(str(f['doc']).split()))}")
        arm_lines.extend(javadoc(
            (desc or f"The {value!r} arm of {type_name}."), "", tags))
        arm_lines.append("@JsonIgnoreProperties(ignoreUnknown = true)")
        arm_lines.append("@JsonInclude(JsonInclude.Include.NON_NULL)")
        arm_lines.append(f"public record {arm}(")
        components = [f'        @JsonProperty("{tag}") String {member(tag)}'] + [
            f'        @JsonProperty("{f["wire"]}") '
            + ("" if f["required"] else "@Nullable ") + f'{f["type"]} {f["name"]}'
            for f in fields
        ]
        arm_lines.append(",\n".join(components))
        arm_lines.append(f") implements {type_name} {{")
        arm_lines.append("}")
        arm_body = "\n".join(arm_lines)
        arm_header = [BANNER.rstrip("\n"), f"package {MODELS_PACKAGE};", "",
                      "import com.fasterxml.jackson.annotation.JsonIgnoreProperties;",
                      "import com.fasterxml.jackson.annotation.JsonInclude;",
                      "import com.fasterxml.jackson.annotation.JsonProperty;"]
        if "@Nullable" in arm_body:
            arm_header.append("import org.jspecify.annotations.Nullable;")
        arm_imports = model_imports(arm_body)
        if arm_imports:
            arm_header.append("")
            arm_header.extend(f"import {fqn};" for fqn in arm_imports)
        arm_header.append("")
        files[f"{MODELS_DIR}/{arm}.java"] = "\n".join(arm_header + [arm_body]) + "\n"
    return files


def emit_models() -> dict[str, str]:
    """Every generated model file, keyed by repository-relative path."""
    secrets = sensitive_map()
    replacements = replacement_schemas()
    files: dict[str, str] = {}
    for name in schema_closure():
        schema = SCHEMAS[name]
        if "enum" in schema and schema.get("type") == "string":
            files[f"{MODELS_DIR}/{pascal(name)}.java"] = emit_enum(name, schema)
            continue
        union = discriminated(schema)
        if union:
            files.update(emit_union(name, schema, union[0], union[1]))
            continue
        files[f"{MODELS_DIR}/{pascal(name)}.java"] = emit_record(
            name, secrets.get(name, set()), name in replacements)
    return files


