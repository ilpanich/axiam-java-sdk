def build() -> dict[Path, str]:
    """Every file this generator owns, mapped to its current content."""
    files: dict[Path, str] = {}
    for path, body in emit_models().items():
        files[ROOT / path] = body
    for ns, nsdef in REGISTRY["namespaces"].items():
        files[ROOT / f"{API_DIR}/{pascal(ns)}Api.java"] = emit_namespace(ns, nsdef)
    files[ROOT / f"{API_DIR}/ManagementApi.java"] = emit_api()
    files[ROOT / f"{TEST_DIR}/ManagementSurfaceGeneratedTest.java"] = emit_test()
    files[ROOT / f"{TEST_DIR}/ManagementSparseBodiesGeneratedTest.java"] = emit_sparse_test()
    return files


def prune(files: dict[Path, str]) -> list[Path]:
    """Generated files on disk that this run no longer produces.

    A schema removed upstream would otherwise leave a stale record behind that
    still compiles, still looks generated, and no longer corresponds to
    anything — the one failure mode a per-file generator has that a
    single-file one does not.
    """
    stale: list[Path] = []
    for directory in (ROOT / MODELS_DIR, ROOT / API_DIR):
        if not directory.exists():
            continue
        for existing in directory.glob("*.java"):
            if existing in files:
                continue
            if existing.read_text().startswith("// @generated by scripts/gen_management.py"):
                stale.append(existing)
    return stale


def main() -> int:
    """Write the generated surface, or verify it is current under ``--check``."""
    PROJECTIONS.update(projection_map())
    files = build()
    stale_extra = prune(files)

    if "--check" in sys.argv:
        stale = [p for p, body in files.items() if not p.exists() or p.read_text() != body]
        stale.extend(stale_extra)
        if stale:
            for path in stale:
                print(f"FAIL: {path.relative_to(ROOT)} is stale", file=sys.stderr)
            print("run `python3 scripts/gen_management.py`", file=sys.stderr)
            return 1
        print(f"OK: {len(files)} generated files are current "
              f"({REGISTRY['operation_count']} operations)")
        return 0

    for path in stale_extra:
        path.unlink()
    for path, body in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body)
    print(f"wrote {len(files)} files: {REGISTRY['operation_count']} operations across "
          f"{REGISTRY['namespace_count']} namespaces")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
