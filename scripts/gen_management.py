def implicit_params(namespace: str, op: dict[str, Any]) -> set[str]:
    """Which of this operation's path params default from the client (§27.4 rule 3)."""
    names = {p["name"] for p in op["path_params"]}
    out: set[str] = set()
    if "org_id" in names:
        out.add("org_id")
    if "tenant_id" in names and namespace in IMPLICIT_TENANT_NAMESPACES:
        out.add("tenant_id")
    return out


def split_query(op: dict[str, Any]) -> tuple[list[Any], list[Any]]:
    """This operation's non-paging query params, split required / optional."""
    extra = extra_query_params(op)
    return [q for q in extra if q["required"]], [q for q in extra if not q["required"]]


def operation_params(namespace: str, opname: str, op: dict[str, Any]) -> list[dict[str, str]]:
    """This operation's caller-facing parameters, in signature order."""
    implicit = implicit_params(namespace, op)
    params: list[dict[str, str]] = []
    for p in op["path_params"]:
        if p["name"] in implicit:
            continue
        java = "java.util.UUID" if p.get("format") == "uuid" else "String"
        params.append({"name": member(p["name"]), "type": java, "wire": p["name"],
                       "doc": f"the {escape(p['name'])} path parameter"})
    required_q, optional_q = split_query(op)
    for q in required_q:
        params.append({"name": member(q["name"]), "type": "String", "wire": q["name"],
                       "doc": f"the required {escape(q['name'])} query parameter"})
    if op["request_body"] == "schema":
        params.append({"name": "body", "type": f"{MODELS_PACKAGE}.{pascal(op['request_schema'])}",
                       "wire": "", "doc": "the request body"})
    elif op["request_body"] == "untyped":
        params.append({"name": "body", "type": "com.fasterxml.jackson.databind.JsonNode",
                       "wire": "", "doc": "the request body, as raw JSON"})
    for q in optional_q:
        params.append({"name": member(q["name"]), "type": "@Nullable String", "wire": q["name"],
                       "doc": f"the optional {escape(q['name'])} query filter, or null to omit it"})
    if op["paginated"]:
        params.append({"name": "page", "type": "@Nullable PageRequest", "wire": "",
                       "doc": "where the page starts and how big it is, or null for the "
                              "server's default"})
    return params


def response_java(op: dict[str, Any]) -> tuple[str, str]:
    """The declared return type and the expression producing it from ``node``."""
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none":
        return "void", ""
    model = f"{MODELS_PACKAGE}.{pascal(schema)}"
    if kind == "array":
        return (f"java.util.List<{model}>",
                f"ManagementSupport.convertList(node, {model}.class, operation)")
    if kind == "page":
        return (f"Page<{model}>",
                f"ManagementSupport.convertPage(node, {model}.class, operation)")
    return model, f"ManagementSupport.convert(node, {model}.class, operation)"


def operation_doc(op: dict[str, Any]) -> str:
    """The Javadoc body for one generated operation."""
    text = f"Issues {op['method']} {op['path']}."
    if op["update_style"] == "replace":
        text += ("\n\nThis is a REPLACEMENT, not a patch (§27.4 rule 5). Every field of the "
                 "body is required, and what you do not carry over from a prior read is not "
                 "preserved -- it is overwritten. Read first, change the field you mean, send "
                 "the whole thing back.")
    if op["sensitive_response_fields"]:
        joined = ", ".join(op["sensitive_response_fields"])
        text += (f"\n\nReturns secret material, once. {joined} is returned by this call and by "
                 f"no other; no later get will return it again, and the get projection has no "
                 f"field where it was. Discarding the result destroys the credential "
                 f"(§27.5 rule 3).")
    if op["method"] != "GET":
        text += ("\n\nNot retried on failure (§27.4 rule 8): every write on this surface is "
                 "issued exactly once, including the ones that look idempotent.")
    return text


def emit_namespace(namespace: str, nsdef: dict[str, Any]) -> str:
    """One namespace handle class."""
    handle = f"{pascal(namespace)}Api"
    ops = nsdef["operations"]
    has_org = any("org_id" in implicit_params(namespace, o) for o in ops.values())
    has_tenant = any("tenant_id" in implicit_params(namespace, o) for o in ops.values())

    lines = [BANNER.rstrip("\n"), f"package {API_PACKAGE};", "",
             "import com.fasterxml.jackson.databind.JsonNode;",
             "import io.axiam.sdk.internal.ManagementTransport;",
             "import org.jspecify.annotations.Nullable;", "",
             "import java.util.LinkedHashMap;", "import java.util.Map;", "import java.util.UUID;", ""]
    lines.extend(javadoc(
        f"The {namespace} management namespace (CONTRACT §27.1).\n\n{nsdef['doc']}\n\n"
        f"Acquiring a handle performs no I/O and allocates nothing meaningful "
        f"(§27.2 rule 1); it holds the transport and cannot be constructed "
        f"without one.\n\nEvery operation here is synchronous. The SDK's "
        f"CompletableFuture twins exist only on the §1 core operations, so the "
        f"async form of a management call is "
        f"CompletableFuture.supplyAsync(() -> client.management().{camel(namespace)}()...) "
        f"— one line, rather than 147 more methods to keep in step."))
    lines.append(f"public final class {handle} {{")
    lines.append("")
    lines.append("    private final ManagementTransport transport;")
    lines.append("    private final NamespaceScope scope;")
    lines.append("")
    lines.append(f"    {handle}(ManagementTransport transport, NamespaceScope scope) {{")
    lines.append("        this.transport = transport;")
    lines.append("        this.scope = scope;")
    lines.append("    }")
    lines.append("")

    if has_org:
        lines.extend(javadoc(
            "Addresses a different organization than the client's own.\n\n§27.4 rule 3: the "
            "client's organization is the default, and a platform-admin token legitimately "
            "overrides it.",
            "    ", ["@param orgId the organization to address",
                    "@return a new handle; this one is unchanged"]))
        lines.append(f"    public {handle} inOrg(UUID orgId) {{")
        lines.append(f"        return new {handle}(transport, scope.withOrg(orgId));")
        lines.append("    }")
        lines.append("")
    if has_tenant:
        lines.extend(javadoc(
            "Addresses a different tenant than the client's own (§27.4 rule 3).",
            "    ", ["@param tenantId the tenant to address",
                    "@return a new handle; this one is unchanged"]))
        lines.append(f"    public {handle} forTenant(UUID tenantId) {{")
        lines.append(f"        return new {handle}(transport, scope.withTenant(tenantId));")
        lines.append("    }")
        lines.append("")

    for opname, op in ops.items():
        lines.extend(emit_operation(namespace, opname, op))
    lines.append("}")
    return "\n".join(lines) + "\n"


def emit_operation(namespace: str, opname: str, op: dict[str, Any]) -> list[str]:
    """One generated operation, plus its auto-paging form where it has one."""
    canonical = f"{namespace}.{opname}"
    method_name = member(opname)
    implicit = implicit_params(namespace, op)
    params = operation_params(namespace, opname, op)
    ret, expr = response_java(op)

    signature = ", ".join(f"{p['type']} {p['name']}" for p in params)
    tags = [f"@param {p['name']} {p['doc']}" for p in params]
    if ret != "void":
        tags.append("@return the server's response")
    tags.extend([
        "@throws io.axiam.sdk.errors.AuthError if there is no active session (§27.4 rule 1)",
        "@throws io.axiam.sdk.errors.NotFoundError if the server answers 404",
        "@throws io.axiam.sdk.errors.ConflictError if the server answers 409",
        "@throws io.axiam.sdk.errors.ValidationError if the server answers 400 or 422",
        "@throws io.axiam.sdk.errors.NetworkError on a transport failure or any other "
        "unsuccessful status",
    ])

    lines: list[str] = []
    lines.extend(javadoc(operation_doc(op), "    ", tags))
    lines.append(f"    public {ret} {method_name}({signature}) {{")
    lines.append(f'        final String operation = "{canonical}";')

    route = op["path"]
    for p in op["path_params"]:
        name = p["name"]
        if name in implicit:
            fn = "resolveOrg" if name == "org_id" else "resolveTenant"
            lines.append(f"        UUID {member(name)} = ManagementSupport.{fn}("
                         f"transport, scope, operation);")
            route = route.replace(f"{{{name}}}", f'" + {member(name)} + "')
        elif p.get("format") == "uuid":
            route = route.replace(f"{{{name}}}", f'" + {member(name)} + "')
        else:
            route = route.replace(
                f"{{{name}}}",
                f'" + java.net.URLEncoder.encode({member(name)}, '
                f'java.nio.charset.StandardCharsets.UTF_8) + "')

    required_q, optional_q = split_query(op)
    lines.append("        Map<String, @Nullable String> query = new LinkedHashMap<>();")
    for q in required_q:
        lines.append(f'        query.put("{q["name"]}", {member(q["name"])});')
    for q in optional_q:
        lines.append(f'        query.put("{q["name"]}", {member(q["name"])});')
    if op["paginated"]:
        lines.append("        ManagementSupport.pageQuery(query, page);")

    body_expr = "body" if op["request_body"] != "none" else "null"
    assign = "" if ret == "void" else "JsonNode node = "
    lines.append(f'        {assign}transport.send(operation, "{op["method"]}",')
    lines.append(f'                "{op["path"]}", "{route}", query, {body_expr});')
    if ret != "void":
        lines.append(f"        return {expr};")
    lines.append("    }")
    lines.append("")

    if op["paginated"]:
        inner = ret[len("Page<"):-1]
        lead = [p for p in params if p["name"] != "page"]
        lead_sig = ", ".join(f"{p['type']} {p['name']}" for p in lead)
        lead_sig = (lead_sig + ", " if lead_sig else "") + "@Nullable PageRequest start"
        forward = "".join(f"{p['name']}, " for p in lead)
        all_tags = [f"@param {p['name']} {p['doc']}" for p in lead]
        all_tags.append("@param start where the walk begins, or null to start at the top")
        all_tags.append("@return every item in the set, across as many requests as it takes")
        lines.extend(javadoc(
            f"Walks {canonical} to exhaustion, concatenating every page.\n\nThe auto-paging "
            f"form §27.4 rule 4 requires. It stops on an empty page even if the total "
            f"disagrees, so a misreporting server costs one wasted request rather than an "
            f"unbounded loop.",
            "    ", all_tags))
        lines.append(f"    public java.util.List<{inner}> {method_name}All({lead_sig}) {{")
        lines.append(f"        return ManagementSupport.collectPages(start, p -> "
                     f"{method_name}({forward}p));")
        lines.append("    }")
        lines.append("")
    return lines


