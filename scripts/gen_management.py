        "this guards against is a generator that gets it right for the model somebody "
        "wrote a test for and wrong for the other seventeen.\n\nEach case sets one "
        "field at a time and asserts the body carries exactly that one wire key, then "
        "sets every field and asserts the body carries exactly all of them. Bodies are "
