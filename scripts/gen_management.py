EXAMPLE_UUID = "11111111-1111-4111-8111-111111111111"
EXAMPLE_TIME = "2026-08-26T00:00:00Z"


def example_json(schema: Any, depth: int = 0) -> Any:
    """A minimal server response body satisfying ``schema``."""
    if depth > 6 or not schema:
        return None
    if "$ref" in schema:
        return example_json(resolve_ref(schema), depth + 1)
    inner = nullable_ref(schema)
    if inner:
        return example_json(SCHEMAS.get(inner, {}), depth + 1)
    if "enum" in schema:
        return schema["enum"][0]
    variants = schema.get("oneOf") or schema.get("anyOf")
    if variants:
        first = next((v for v in variants if v.get("type") != "null"), None)
        return example_json(first, depth + 1) if first else None
    if "allOf" in schema:
        merged: dict[str, Any] = {}
        for part in schema["allOf"]:
            got = example_json(part, depth + 1)
            if isinstance(got, dict):
                merged.update(got)
        required = set(schema.get("required") or [])
        for name, prop in (schema.get("properties") or {}).items():
            if name in required:
                merged[name] = example_json(prop, depth + 1)
        return merged
    kind = schema.get("type")
    if isinstance(kind, list):
        kind = next((k for k in kind if k != "null"), None)
    if kind == "object" or (not kind and "properties" in schema):
        required = set(schema.get("required") or [])
        return {n: example_json(p, depth + 1)
                for n, p in (schema.get("properties") or {}).items() if n in required}
    if kind == "array":
        return []
    if kind in ("integer", "number"):
        return 1
    if kind == "boolean":
        return True
    if kind == "string":
        if schema.get("format") == "uuid":
            return EXAMPLE_UUID
        if schema.get("format") == "date-time":
            return EXAMPLE_TIME
        return "example"
    return {}


def example_response(op: dict[str, Any]) -> str:
    """A Java string literal for the response body the conformance test mounts."""
    kind, schema = op["response"]["kind"], op["response"]["schema"]
    if kind == "none":
        return '""'
    one = example_json(SCHEMAS.get(schema, {}))
    payload: Any = one
    if kind == "array":
        payload = [one]
    elif kind == "page":
        payload = {"items": [one], "total": 1, "offset": 0, "limit": 50}
    return json.dumps(json.dumps(payload))


def java_literal(schema: Any, secrets: set[str], field: str | None = None, depth: int = 0) -> str:
    """A Java expression building a minimal valid value for a schema."""
    if depth > 6:
        return "null"
    if field and field in secrets:
        return 'io.axiam.sdk.Sensitive.of("example")'
    if "$ref" in schema:
        return literal_for(schema["$ref"].split("/")[-1], set(), depth + 1)
    if nullable_ref(schema) or "oneOf" in schema or "anyOf" in schema:
        return "null"
    kind = schema.get("type")
    if isinstance(kind, list):
        if "null" in kind:
            return "null"
        kind = next(iter(kind), None)
    if "enum" in schema:
        return "null"
    if kind == "array":
        return "java.util.List.of()"
    if kind == "integer":
        return "1L" if schema.get("format") == "int64" else "1"
    if kind == "number":
        return "1.0"
    if kind == "boolean":
        return "true"
    if kind == "string":
        if schema.get("format") == "uuid":
            return "EXAMPLE_ID"
        if schema.get("format") == "date-time":
            return f'java.time.OffsetDateTime.parse("{EXAMPLE_TIME}")'
        return '"example"'
    return "null"


def literal_for(name: str, secrets: set[str], depth: int = 0) -> str:
    """A Java expression constructing a minimal valid instance of ``name``."""
    schema = SCHEMAS.get(name, {})
    type_name = f"{MODELS_PACKAGE}.{pascal(name)}"
    if "enum" in schema and schema.get("type") == "string":
        return f"{type_name}.{enum_constant(schema['enum'][0])}"
    union = discriminated(schema)
    if union:
        tag, arms = union
        value, payload = arms[0]
        arm = f"{type_name}{pascal(value)}"
        if "$ref" in payload:
            aprops, arequired, _ = flatten(payload["$ref"].split("/")[-1])
        else:
            aprops = payload.get("properties") or {}
            arequired = set(payload.get("required") or [])
        args = [f'"{value}"']
        for wire in sorted(aprops):
            if wire == tag:
                continue
            args.append(java_literal(aprops[wire], set(), wire, depth + 1)
                        if wire in arequired else "null")
        return f"new {arm}({', '.join(args)})"
    props, required, _ = flatten(name)
    args = []
    for wire in sorted(props):
        if wire in secrets:
            args.append('io.axiam.sdk.Sensitive.of("example")')
        elif wire in required:
            args.append(java_literal(props[wire], secrets, wire, depth + 1))
        else:
            args.append("null")
    return f"new {type_name}({', '.join(args)})"


def call_arguments(namespace: str, opname: str, op: dict[str, Any],
                   secrets: dict[str, set[str]]) -> tuple[list[str], str]:
    """The conformance test's positional arguments, and the route it mounts."""
    implicit = implicit_params(namespace, op)
    args: list[str] = []
    route = op["path"]
    for p in op["path_params"]:
        name = p["name"]
        if name in implicit:
            token = "ORG_ID" if name == "org_id" else "TENANT_ID"
            route = route.replace(f"{{{name}}}", f'" + {token} + "')
            continue
        if p.get("format") == "uuid":
            args.append("EXAMPLE_ID")
            route = route.replace(f"{{{name}}}", '" + EXAMPLE_ID + "')
        else:
            args.append('"example"')
            route = route.replace(f"{{{name}}}", "example")
    required_q, optional_q = split_query(op)
    args.extend('"example"' for _ in required_q)
    if op["request_body"] == "schema":
        args.append(literal_for(op["request_schema"], secrets.get(op["request_schema"], set())))
    elif op["request_body"] == "untyped":
        args.append("io.axiam.sdk.internal.ManagementTransport.reader().createObjectNode()")
    args.extend("null" for _ in optional_q)
    if op["paginated"]:
        args.append("PageRequest.of(50)")
    return args, route


