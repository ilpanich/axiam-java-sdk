def sparse_models() -> list[tuple[str, list[dict[str, Any]]]]:
    """Every schema whose components are all optional -- the sparse bodies."""
    secrets = sensitive_map()
    out: list[tuple[str, list[dict[str, Any]]]] = []
    for name in schema_closure():
        schema = SCHEMAS[name]
        if "enum" in schema and schema.get("type") == "string":
            continue
        if discriminated(schema):
            continue
        fields, required, _ = field_list(name, secrets.get(name, set()))
        if fields and not required:
            out.append((name, fields))
    return out


def builder_literal(schema: Any, wire: str, secrets: set[str]) -> str:
    """A NON-null Java literal for a sparse field.

    ``java_literal`` is allowed to answer ``null`` -- it fills optional
    components of a request the surface test only needs to be well-formed. Here
    null is the one answer that cannot be used: the whole assertion is that a
    field which WAS set reaches the wire, and a null one is omitted by design.
    """
    if wire in secrets:
        return 'io.axiam.sdk.Sensitive.of("example")'
    ref = schema["$ref"].split("/")[-1] if "$ref" in schema else nullable_ref(schema)
    if ref and ref in SCHEMAS:
        return literal_for(ref, set())
    rendered = java_type(schema)
    if rendered.startswith("List<"):
        return "java.util.List.of()"
    return {
        "UUID": "EXAMPLE_ID",
        "OffsetDateTime": f'java.time.OffsetDateTime.parse("{EXAMPLE_TIME}")',
        "String": '"example"',
        "Long": "1L",
        "Integer": "1",
        "Double": "1.0",
        "Boolean": "true",
        "JsonNode": "JSON.createObjectNode()",
    }[rendered]


def emit_sparse_test() -> str:
    """The generated §27.4 rule 5 conformance test, one case per sparse body."""
    secrets = sensitive_map()
    models = sparse_models()
