    @Test
    void discoverySuppliesTheJwksUriAndMustNameTheIssuer() throws Exception {
        OctetKeyPair key = key();
        jwks(key);
        ObjectNode doc = MAPPER.createObjectNode();
        doc.put("issuer", ISSUER);
        doc.put("jwks_uri", server.base() + "/oauth2/jwks");
        server.on("GET", "/.well-known/ssf-configuration", json(200, doc.toString()));
        SsfReceiver r = new SsfReceiver(client, SsfReceiverConfig.builder(ISSUER, AUDIENCE,
                SsfKeySource.discoveryUrl(server.base() + "/.well-known/ssf-configuration")).build());
        r.verifySet(signSet(key, claims()));

        SsfReceiver wrong = new SsfReceiver(client, SsfReceiverConfig.builder("https://someone-else.test", AUDIENCE,
                SsfKeySource.discoveryUrl(server.base() + "/.well-known/ssf-configuration")).build());
        NetworkError e = assertThrows(NetworkError.class, () -> wrong.verifySet(signSet(key, claims())));
        assertFalse(e instanceof ValidationError);
        // A poll with no token provider is refused locally.
        assertThrows(AuthError.class, () -> wrong.poll("s", SsfPollOptions.none()));
        assertTrue(wrong.toString().startsWith("SsfReceiver["));
        assertTrue(SsfKeySource.discoveryUrl("https://d").toString().contains("discoveryUrl"));
    }

    @Test
    void aJwksFetchFailureIsANetworkErrorNotARefusal() throws Exception {
        OctetKeyPair key = key();
        server.on("GET", "/oauth2/jwks", json(500, "{}"));
        assertThrows(NetworkError.class, () -> receiver().verifySet(signSet(key, claims())));
        server.on("GET", "/oauth2/jwks", json(200, "{\"keys\":\"nope\"}"));
        assertThrows(NetworkError.class, () -> receiver().verifySet(signSet(key, claims())));
        SsfReceiver plain = new SsfReceiver(client, SsfReceiverConfig.builder(ISSUER, AUDIENCE,
                SsfKeySource.jwksUri("http://keys.example.test/jwks")).build());
        assertThrows(NetworkError.class, () -> plain.verifySet(signSet(key, claims())), "https is required");
        SsfReceiver garbage = new SsfReceiver(client, SsfReceiverConfig.builder(ISSUER, AUDIENCE,
                SsfKeySource.jwksUri("not a url")).build());
        assertThrows(NetworkError.class, () -> garbage.verifySet(signSet(key, claims())));
        server.on("GET", "/no-jwks", json(200, "{\"issuer\":\"" + ISSUER + "\"}"));
        SsfReceiver noJwks = new SsfReceiver(client, SsfReceiverConfig.builder(ISSUER, AUDIENCE,
                SsfKeySource.discoveryUrl(server.base() + "/no-jwks")).build());
        assertThrows(NetworkError.class, () -> noJwks.verifySet(signSet(key, claims())));
    }

    @Test
    void pushErrorCodesAreRfc8935Codes() {
        Map<SetFailureReason, String> expected = Map.of(
                SetFailureReason.MALFORMED, "invalid_request",
                SetFailureReason.INVALID_TYPE, "invalid_request",
                SetFailureReason.REPLAYED, "invalid_request",
                SetFailureReason.INVALID_KEY, "invalid_key",
                SetFailureReason.INVALID_ISSUER, "invalid_issuer",
                SetFailureReason.INVALID_AUDIENCE, "invalid_audience",
                SetFailureReason.INVALID_REQUEST, "invalid_request");
        expected.forEach((reason, code) -> {
            assertEquals(code, reason.pushErrorCode());
            assertEquals(code, SetErr.fromReason(reason).err());
        });
        assertEquals("replayed", SetFailureReason.REPLAYED.code());
        assertEquals(8, List.of(SsfEventTypes.SESSION_REVOKED, SsfEventTypes.CREDENTIAL_CHANGE,
                SsfEventTypes.ASSURANCE_LEVEL_CHANGE, SsfEventTypes.ACCOUNT_DISABLED, SsfEventTypes.ACCOUNT_ENABLED,
                SsfEventTypes.ACCOUNT_PURGED, SsfEventTypes.VERIFICATION, SsfEventTypes.STREAM_UPDATED).size());
    }
