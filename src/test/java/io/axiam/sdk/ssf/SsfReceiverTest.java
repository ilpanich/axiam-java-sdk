    private static OctetKeyPair key() throws Exception {
        return new OctetKeyPairGenerator(Curve.Ed25519).keyID("k-" + UUID.randomUUID()).generate();
    }

    private static OctetKeyPair keyWithKid(String kid) throws Exception {
        return new OctetKeyPairGenerator(Curve.Ed25519).keyID(kid).generate();
    }

    private static ObjectNode claims() {
        ObjectNode c = MAPPER.createObjectNode();
        c.put("iss", ISSUER);
        c.put("aud", AUDIENCE);
        c.put("iat", 1_791_500_000L);
        c.put("jti", UUID.randomUUID().toString().replace("-", ""));
        c.put("txn", "t-1");
        ObjectNode sub = c.putObject("sub_id");
        sub.put("format", "iss_sub");
        sub.put("iss", ISSUER);
        sub.put("sub", UUID.randomUUID().toString());
        c.putObject("events").putObject(SsfEventTypes.SESSION_REVOKED).put("event_timestamp", 1_791_500_000L);
        return c;
    }

    private static String sign(OctetKeyPair key, JWSHeader header, JsonNode claims) throws Exception {
        JWSObject jws = new JWSObject(header, new Payload(claims.toString()));
        jws.sign(new Ed25519Signer(key));
        return jws.serialize();
    }

    private static String signSet(OctetKeyPair key, JsonNode claims) throws Exception {
        return sign(key, new JWSHeader.Builder(JWSAlgorithm.EdDSA)
                .type(new JOSEObjectType("secevent+jwt")).keyID(key.getKeyID()).build(), claims);
    }

    private RouteServer.Route jwks(OctetKeyPair... keys) {
        List<com.nimbusds.jose.jwk.JWK> pub = new ArrayList<>();
        for (OctetKeyPair k : keys) {
            pub.add(k.toPublicJWK());
        }
        return server.on("GET", "/oauth2/jwks", json(200, new JWKSet(pub).toString()));
    }

    private SsfReceiver receiver() {
        String token = "cc-" + UUID.randomUUID();
        return new SsfReceiver(client, SsfReceiverConfig.builder(ISSUER, AUDIENCE,
                        SsfKeySource.jwksUri(server.base() + "/oauth2/jwks"))
                .accessTokenProvider(() -> Sensitive.of(token)).build());
    }

    private static SetFailureReason reason(SsfReceiver r, String set) {
        SetVerificationError e = assertThrows(SetVerificationError.class, () -> r.verifySet(set));
        assertInstanceOf(AuthError.class, e);
        assertEquals(e.failureReason().code(), e.reason());
        return e.failureReason();
    }

    private static ObjectNode with(ObjectNode c, String k, Object v) {
        ObjectNode copy = c.deepCopy();
        copy.set(k, MAPPER.valueToTree(v));
        return copy;
    }

    private static ObjectNode without(ObjectNode c, String k) {
        ObjectNode copy = c.deepCopy();
        copy.remove(k);
        return copy;
    }

    // ── 1 ──
    @Test
    void aSetSignedByTheJwksKeyVerifiesIntoItsClaims() throws Exception {
        OctetKeyPair key = key();
        jwks(key);
        ObjectNode c = claims();
        SsfReceiver r = receiver();
        SecurityEvent event = r.verifySet(signSet(key, c));
        assertEquals(c.path("jti").asText(), event.jti());
        assertEquals(1_791_500_000L, event.iat());
        assertEquals(ISSUER, event.iss());
        assertEquals(MAPPER.getNodeFactory().textNode(AUDIENCE), event.aud());
        assertEquals("t-1", event.txn());
        assertEquals(SsfEventTypes.SESSION_REVOKED, event.eventType());
        assertEquals(c.path("events").path(SsfEventTypes.SESSION_REVOKED).toString(), event.event().toString());
        assertEquals(c.path("sub_id"), event.subId());

        // An aud array containing the audience, the media-type spelling of typ
        // in any case, and no txn.
        ObjectNode arr = without(with(claims(), "aud", List.of("other", AUDIENCE)), "txn");
        SecurityEvent second = r.verifySet(sign(key, new JWSHeader.Builder(JWSAlgorithm.EdDSA)
                .type(new JOSEObjectType("Application/SecEvent+JWT")).keyID(key.getKeyID()).build(), arr));
        assertTrue(second.aud().isArray());
        assertNull(second.txn());
    }

    // ── 2 ──
    @Test
    void aWrongTypOrAlgIsRefusedInThatOrder() throws Exception {
        OctetKeyPair key = key();
        jwks(key);
        SsfReceiver r = receiver();
        ObjectNode c = claims();
        assertEquals(SetFailureReason.INVALID_TYPE,
                reason(r, sign(key, new JWSHeader.Builder(JWSAlgorithm.EdDSA).keyID(key.getKeyID()).build(), c)));
        assertEquals(SetFailureReason.INVALID_TYPE, reason(r, sign(key, new JWSHeader.Builder(JWSAlgorithm.EdDSA)
                .type(JOSEObjectType.JWT).keyID(key.getKeyID()).build(), c)));
        String payload = B64.encodeToString(c.toString().getBytes(StandardCharsets.UTF_8));
        String none = B64.encodeToString("{\"alg\":\"none\",\"typ\":\"secevent+jwt\"}"
                .getBytes(StandardCharsets.UTF_8)) + "." + payload + ".";
        assertEquals(SetFailureReason.INVALID_KEY, reason(r, none));
        byte[] macKey = new byte[32];
        new SecureRandom().nextBytes(macKey);
        JWSObject hs = new JWSObject(new JWSHeader.Builder(JWSAlgorithm.HS256)
                .type(new JOSEObjectType("secevent+jwt")).keyID(key.getKeyID()).build(), new Payload(c.toString()));
        hs.sign(new MACSigner(macKey));
        assertEquals(SetFailureReason.INVALID_KEY, reason(r, hs.serialize()));
        assertEquals(SetFailureReason.MALFORMED, reason(r, "a.b"));
        assertEquals(SetFailureReason.MALFORMED, reason(r, "!!.@@.##"));
        assertEquals(SetFailureReason.MALFORMED, reason(r, B64.encodeToString("[]".getBytes(StandardCharsets.UTF_8))
                + "." + payload + ".AA"));
        assertEquals(SetFailureReason.INVALID_KEY, reason(r, B64.encodeToString(
                "{\"alg\":\"EdDSA\",\"typ\":\"secevent+jwt\"}".getBytes(StandardCharsets.UTF_8)) + "." + payload + ".AA"),
                "no kid");
    }

